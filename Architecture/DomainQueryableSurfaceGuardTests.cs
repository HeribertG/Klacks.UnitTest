/// <summary>
/// Guards that the Domain layer neither composes database queries nor hands out a composable query
/// (.claude/rules/backend-architecture.md; clean-architecture audit, docs/knowledge/iqueryable-leak-removal-pattern-2026-10-22.md).
/// A query composer is shaped for the SQL provider (ToLower for lower(), ?? "" for coalesce, EF function mappings,
/// Where(_ => false) to keep the provider alive) and belongs next to its repository in Infrastructure; a domain rule
/// that both reads and in-memory code share is exposed as an Expression (ShiftGroupVisibilityFilter.VisibleTo), not as
/// an IQueryable. Two checks with shrink-only allowlists (target: empty):
/// - reflection: no public or protected member of a Domain type (interfaces, classes, static helpers, records; types
///   generated by the compiler excluded) carries a queryable in its signature - return type, parameter, property,
///   field, generic argument, tuple element, delegate or array;
/// - source: the Domain source (comments and string literals blanked) names neither IQueryable, IOrderedQueryable
///   nor AsQueryable, so private query composition is caught as well.
/// An allowlist entry that no longer occurs fails too: remove it in the same change that fixes the type.
/// </summary>

using System.Text.RegularExpressions;
using Klacks.Api.Domain.Interfaces;
using Klacks.UnitTest.TestHelpers;

namespace Klacks.UnitTest.Architecture;

[TestFixture]
public class DomainQueryableSurfaceGuardTests
{
    private const string DomainFolder = "Domain";
    private const string DomainNamespace = "Klacks.Api.Domain";
    private const int MinimumDomainFiles = 1000;
    private const int MinimumDomainTypes = 1000;
    private const string ShrinkOnlyHint =
        "The allowlist may only LOSE entries. Move the query composer next to its repository in Infrastructure, or expose " +
        "the domain rule as an Expression<Func<T, bool>> that Infrastructure applies with Where.";

    private static readonly string[] ExcludedPathFragments =
    [
        $"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}",
        $"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}",
    ];

    private static readonly IReadOnlySet<string> KnownExposedMembers = new HashSet<string>(StringComparer.Ordinal)
    {
    };

    private static readonly IReadOnlySet<string> KnownSourceFiles = new HashSet<string>(StringComparer.Ordinal)
    {
    };

    private static readonly Regex QueryableName = new(
        @"\b(?:IQueryable|IOrderedQueryable|AsQueryable)\b",
        RegexOptions.Compiled | RegexOptions.CultureInvariant,
        TimeSpan.FromSeconds(1));

    [Test]
    public void DomainTypes_ExposeNoQueryable()
    {
        var unexpected = ExposedMembers().Where(member => !KnownExposedMembers.Contains(member)).ToList();

        unexpected.ShouldBeEmpty(
            "These Domain members hand out or take an IQueryable:" +
            $"{Environment.NewLine}{string.Join(Environment.NewLine, unexpected)}{Environment.NewLine}{ShrinkOnlyHint}");
    }

    [Test]
    public void KnownExposedMembers_ListOnlyMembersThatStillExpose()
    {
        var current = ExposedMembers().ToHashSet(StringComparer.Ordinal);
        var stale = KnownExposedMembers.Where(member => !current.Contains(member)).OrderBy(member => member, StringComparer.Ordinal).ToList();

        stale.ShouldBeEmpty(
            $"These allowlist entries no longer occur - delete them:{Environment.NewLine}{string.Join(Environment.NewLine, stale)}");
    }

    [Test]
    public void DomainSource_NamesNoQueryable()
    {
        var unexpected = SourceFindings()
            .Where(finding => !KnownSourceFiles.Contains(finding.RelativePath))
            .Select(finding => finding.Text)
            .ToList();

        unexpected.ShouldBeEmpty(
            "The Domain composes no database query:" +
            $"{Environment.NewLine}{string.Join(Environment.NewLine, unexpected)}{Environment.NewLine}{ShrinkOnlyHint}");
    }

    [Test]
    public void KnownSourceFiles_ListOnlyFilesThatStillNameAQueryable()
    {
        var current = SourceFindings().Select(finding => finding.RelativePath).ToHashSet(StringComparer.Ordinal);
        var stale = KnownSourceFiles.Where(path => !current.Contains(path)).OrderBy(path => path, StringComparer.Ordinal).ToList();

        stale.ShouldBeEmpty(
            $"These allowlist entries no longer occur - delete them:{Environment.NewLine}{string.Join(Environment.NewLine, stale)}");
    }

    [Test]
    public void Scan_CoversTheDomainLayer()
    {
        DomainFiles().Count.ShouldBeGreaterThan(MinimumDomainFiles, "The Domain source scan found too few files.");
        DomainTypes().Count.ShouldBeGreaterThan(MinimumDomainTypes, "The Domain reflection scan found too few types.");
    }

    [Test]
    public void ReflectionCheck_FindsQueryablesInEveryMemberKind()
    {
        QueryableSignatureInspector.ExposedQueryableMembers(typeof(ProbeComposer)).ShouldBe(
            new[]
            {
                "ProbeComposer.Compose",
                "ProbeComposer.Sorted",
                "ProbeComposer.Source",
            },
            ignoreOrder: true);
        QueryableSignatureInspector.ExposedQueryableMembers(typeof(ProbeRule)).ShouldBeEmpty();
        QueryableSignatureInspector.IsCompilerGenerated(typeof(ProbeComposer)).ShouldBeFalse();
    }

    private static List<string> ExposedMembers()
    {
        return DomainTypes()
            .SelectMany(type => QueryableSignatureInspector.ExposedQueryableMembers(type)
                .Select(member => $"{type.Namespace}.{member}"))
            .Distinct(StringComparer.Ordinal)
            .OrderBy(member => member, StringComparer.Ordinal)
            .ToList();
    }

    private static List<Type> DomainTypes()
    {
        return typeof(IUnitOfWork).Assembly.GetTypes()
            .Where(type => type.Namespace != null
                           && (type.Namespace == DomainNamespace || type.Namespace.StartsWith(DomainNamespace + ".", StringComparison.Ordinal)))
            .Where(type => !QueryableSignatureInspector.IsCompilerGenerated(type))
            .ToList();
    }

    private static List<(string RelativePath, string Text)> SourceFindings()
    {
        return DomainFiles()
            .SelectMany(file => file.Lines
                .Select((line, index) => (line, index))
                .Where(entry => QueryableName.IsMatch(entry.line))
                .Select(entry => (file.RelativePath, $"{file.RelativePath}:{entry.index + 1}: {entry.line.Trim()}")))
            .ToList();
    }

    private static List<SourceFile> DomainFiles()
    {
        var root = RepositoryRootLocator.ApiProject;
        var domainRoot = Path.Combine(root, DomainFolder);
        return Directory.EnumerateFiles(domainRoot, "*.cs", SearchOption.AllDirectories)
            .Where(path => !ExcludedPathFragments.Any(path.Contains))
            .Select(path =>
            {
                var code = CSharpSourceBlanker.BlankCommentsAndStrings(File.ReadAllText(path));
                return new SourceFile(Path.GetRelativePath(root, path).Replace('\\', '/'), code.Split('\n'));
            })
            .ToList();
    }

    private sealed record SourceFile(string RelativePath, string[] Lines);

    public class ProbeComposer
    {
        public IOrderedQueryable<int>? Sorted { get; set; }

        protected IQueryable<string>? Source;

        public Task<(IQueryable<string> Rows, int Total)> Compose(Func<Guid, IQueryable<object>> fetch) => throw new NotSupportedException();

        private IQueryable<int> Hidden() => throw new NotSupportedException();
    }

    public static class ProbeRule
    {
        public static System.Linq.Expressions.Expression<Func<string, bool>> Matches(string text) => value => value == text;

        public static bool IsMatch(IEnumerable<string> values, string text) => values.Contains(text);
    }
}
